#!/usr/bin/env python3
"""Export the cross-engine golden vector.

Python is the reference engine; the Rust port must agree with it. Bit-parity is
impossible for anything stochastic (Mersenne Twister vs ChaCha8), so the golden
vector uses a fixed-hit cell at humanize=0, swing=0, vary=0, no fill — the
configuration with the least randomness in it.

It is NOT zero randomness, and that surprised us: `humanize_velocity` floors
`scaled_variance` at 3 (see `Humanizer.humanize_velocity`), so every hit still draws
`randint(center-3, center+3)` even at humanize=0. Ticks, instruments, event
order and MIDI note numbers are therefore fully deterministic and pinned
exactly; velocities can differ between the engines by at most 6 (±3 each way)
and the Rust test allows exactly that much drift and no more.

Writes plugin/fixtures/golden_vector.json. Regenerate (and re-verify BOTH test
suites) only when the reference engine's output is intentionally changed:

    python export_golden.py            # rewrite the fixture
    python export_golden.py --check    # write nothing; exit 1 if it is stale
"""

import argparse
import json
import sys
import os

import arrangement_gen
from assembler import assemble

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "plugin", "fixtures", "golden_vector.json")
KIT = os.path.join(HERE, "kit_mappings", "ugritone.json")

_COMMON = {"humanize": 0.0, "swing": 0.0, "fill_every": 0, "vary": 0.0}

VECTORS = [
    # A fixed-hit 4/4 cell with four instruments including ghost snares — enough
    # vocabulary that a divergence in velocity levels or bar math shows up.
    {"cell_name": "raein_melodic_drive", "bars": 2, "tempo": 120, "time_sig": "4/4",
     "seed": 0, **_COMMON},
    # A Euclidean cell in 7/8 over 4 bars. Euclidean realization consumes no RNG,
    # so its placement is pinned exactly; four bars of co-prime limbs phasing in
    # an odd /8 meter exercise the /8 tick math, bar starts, the seed-derived
    # dice rotation and the Euclidean port, none of which vector 1 touches.
    {"cell_name": "euclid_math_7_8", "bars": 4, "tempo": 140, "time_sig": "7/8",
     "seed": 3, **_COMMON},
]


# Generated song forms: (shape, form seed, style, home meter, meter auto) ->
# arrangement string. Integer dice (SplitMix64), so these match EXACTLY.
FORM_SEEDS = [0, 1, 2, 42, 1234, 9999]
FORM_STYLES = ["fugazi", "posthardcore", "kidcrash", "zona"]


def build_forms():
    cases = []
    for shape in arrangement_gen.FORMS:
        for seed in FORM_SEEDS:
            runs = [(style, (4, 4), True) for style in FORM_STYLES]
            # A forced meter, and a host whose meter is 7/8 (4/4 becomes a turn).
            runs += [("fugazi", (4, 4), False), ("fugazi", (7, 8), True)]
            for style, home, auto in runs:
                form = arrangement_gen.generate_form(shape, seed, style=style, home=home,
                                                     meter_auto=auto)
                cases.append({"shape": shape, "form_seed": seed, "style": style,
                              "home": list(home), "meter_auto": auto, "form": form})
    return cases


def build_one(params):
    kit = json.load(open(KIT))["mapping"]
    res = assemble(**params)
    events = [[tick, kit[inst], vel, inst] for tick, inst, vel in res["events"]]
    return {"params": params, "time_signatures": res["time_signatures"], "events": events}


def build():
    return {
        "_comment": "Generated by export_golden.py — do not hand-edit.",
        "vectors": [build_one(p) for p in VECTORS],
        "forms": build_forms(),
    }


def is_current():
    """True when the committed fixture matches what the engine produces now."""
    try:
        with open(OUT) as f:
            on_disk = json.load(f)
    except (OSError, ValueError):
        return False
    return on_disk == json.loads(json.dumps(build()))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Export the cross-engine golden vector.")
    parser.add_argument("--check", action="store_true",
                        help="Write nothing; exit 1 if the fixture is stale (what CI runs)")
    if parser.parse_args().check:
        if is_current():
            print(f"{OUT} is current")
            sys.exit(0)
        print(f"{OUT} is STALE: if the engine change was intended, run "
              "`python export_golden.py`, re-verify BOTH suites, and commit it", file=sys.stderr)
        sys.exit(1)
    data = build()
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        json.dump(data, f, indent=2)
        f.write("\n")
    counts = ", ".join(f"{v['params']['cell_name']}: {len(v['events'])}" for v in data["vectors"])
    print(f"Wrote {OUT} ({counts} events; {len(data['forms'])} forms)")
